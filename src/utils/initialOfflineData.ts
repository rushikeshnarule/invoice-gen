export function getClientId(name: string): string {
  if (!name) return 'client-unknown';
  const slug = name
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\p{M}]+/gu, '-')
    .replace(/^-+|-+$/g, '');
  if (slug) return `client-${slug}`;
  let hash = 0;
  for (let i = 0; i < name.length; i++) {
    hash = (hash << 5) - hash + name.charCodeAt(i);
    hash |= 0;
  }
  return `client-${Math.abs(hash)}`;
}

